#!/usr/bin/env bash
# Store Argo CD's GitHub App credentials for one environment in Secrets Manager.
#
# Argo CD reads this repo as a private repo would be read: with a GitHub App that can only read
# merlion-bank-infra (Contents: read-only). External Secrets copies the credentials into Argo CD's
# namespace (deploy/bootstrap/repo-creds.yaml); the pipeline never reads them.
#
# Run once per environment by an org owner, from a laptop, after creating the App (README). The
# private key is read from the .pem file GitHub downloads; delete that file afterwards. Use a
# separate key per environment, so revoking one doesn't affect the other.
#
# Like the alerting secret, it's deliberately not a Terraform resource: a GitHub App key can't be
# regenerated by code, so the secret has to outlive a staging teardown.
#
#   deploy/bootstrap/put-argocd-github-app.sh staging <app id> <installation id> <key.pem>
set -euo pipefail

ENV="${1:?usage: put-argocd-github-app.sh <staging|prod> <app id> <installation id> <key.pem>}"
APP_ID="${2:?app id missing}"
INSTALLATION_ID="${3:?installation id missing}"
KEY_FILE="${4:?private key file missing}"
case "$ENV" in staging | prod) ;; *) echo "unknown env: $ENV" >&2; exit 1 ;; esac
[[ "$APP_ID" =~ ^[0-9]+$ && "$INSTALLATION_ID" =~ ^[0-9]+$ ]] || { echo "app and installation ids are numbers" >&2; exit 1; }
grep -q "BEGIN RSA PRIVATE KEY" "$KEY_FILE" || { echo "$KEY_FILE isn't a GitHub App private key" >&2; exit 1; }

REGION="us-east-1"
NAME="g4-merlion-$ENV/argocd/github-app"

VALUE="$(jq -n --arg a "$APP_ID" --arg i "$INSTALLATION_ID" --rawfile k "$KEY_FILE" \
  '{github_app_id: $a, github_app_installation_id: $i, github_app_private_key: $k}')"

if aws secretsmanager describe-secret --region "$REGION" --secret-id "$NAME" >/dev/null 2>&1; then
  aws secretsmanager put-secret-value --region "$REGION" --secret-id "$NAME" --secret-string "$VALUE" >/dev/null
  echo "Updated $NAME"
else
  # AWS-managed key (aws/secretsmanager): the env's own key is destroyed with staging.
  # Tags: Project keeps the training account's nightly cleanup away; Environment keeps the other
  # env's roles out (env fence).
  aws secretsmanager create-secret --region "$REGION" --name "$NAME" \
    --description "Argo CD GitHub App credentials for $ENV (set by put-argocd-github-app.sh)" \
    --secret-string "$VALUE" \
    --tags Key=Project,Value=capstone-project-group-04 Key=Team,Value=g4 \
           Key=Environment,Value="$ENV" Key=ManagedBy,Value=script Key=Stack,Value=argocd >/dev/null
  echo "Created $NAME"
fi
echo "Now delete $KEY_FILE."
